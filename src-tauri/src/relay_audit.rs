/// Model identifiers cross both a network trust boundary and, for MCP output,
/// an LLM trust boundary. Keep them deliberately narrower than an arbitrary
/// provider string so a response cannot smuggle prose/instructions through a
/// nominal metadata field.
pub fn is_strict_model_id(value: &str) -> bool {
    let value = value.trim();
    !value.is_empty()
        && value.len() <= 128
        && value.is_ascii()
        && value.bytes().all(|byte| {
            byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'_' | b'.' | b':' | b'+' | b'/')
        })
}

pub fn safe_model_id(value: &str) -> String {
    let value = value.trim();
    if is_strict_model_id(value) {
        value.to_owned()
    } else {
        INVALID_MODEL_ID_SENTINEL.to_owned()
    }
}

