/// Structure-only evidence for Anthropic Messages API thinking blocks.
///
/// Opaque `signature` and `redacted_thinking.data` values are never retained
/// or interpreted. A valid structure is protocol compatibility evidence only;
/// it is not cryptographic model authentication.
#[derive(Clone, Copy, Debug, Default, Deserialize, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub enum AnthropicThinkingStructureState {
    #[default]
    NotObserved,
    Valid,
    Invalid,
}

#[derive(Clone, Copy, Debug, Deserialize, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub enum AnthropicThinkingFinding {
    ThinkingFieldMissing,
    ThinkingFieldWrongType,
    SignatureFieldMissing,
    SignatureFieldWrongType,
    RedactedDataFieldMissing,
    RedactedDataFieldWrongType,
    StreamBlockIndexInvalid,
    StreamBlockIndexReused,
    ThinkingDeltaUnexpected,
    SignatureDeltaUnexpected,
    SignatureDeltaDuplicate,
    RedactedThinkingDeltaUnexpected,
    ThinkingBlockNotClosed,
    RedactedThinkingBlockNotClosed,
}

impl AnthropicThinkingFinding {
    fn protocol_reason(self) -> &'static str {
        match self {
            Self::ThinkingFieldMissing => "Anthropic thinking block is missing the thinking field",
            Self::ThinkingFieldWrongType => {
                "Anthropic thinking block has a non-string thinking field"
            }
            Self::SignatureFieldMissing => {
                "Anthropic thinking block is missing its opaque signature field"
            }
            Self::SignatureFieldWrongType => "Anthropic thinking signature field is not a string",
            Self::RedactedDataFieldMissing => {
                "Anthropic redacted_thinking block is missing its opaque data field"
            }
            Self::RedactedDataFieldWrongType => {
                "Anthropic redacted_thinking data field is not a string"
            }
            Self::StreamBlockIndexInvalid => {
                "Anthropic thinking stream event has a missing or invalid block index"
            }
            Self::StreamBlockIndexReused => {
                "Anthropic thinking stream reused an open content block index"
            }
            Self::ThinkingDeltaUnexpected => {
                "Anthropic thinking_delta did not belong to an open thinking block"
            }
            Self::SignatureDeltaUnexpected => {
                "Anthropic signature_delta did not belong to an open thinking block"
            }
            Self::SignatureDeltaDuplicate => {
                "Anthropic thinking block emitted more than one signature field"
            }
            Self::RedactedThinkingDeltaUnexpected => {
                "Anthropic redacted_thinking block unexpectedly emitted a delta"
            }
            Self::ThinkingBlockNotClosed => {
                "Anthropic thinking stream ended with an open thinking block"
            }
            Self::RedactedThinkingBlockNotClosed => {
                "Anthropic thinking stream ended with an open redacted_thinking block"
            }
        }
    }
}

#[derive(Clone, Debug, Default, Deserialize, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct AnthropicThinkingMetadata {
    pub state: AnthropicThinkingStructureState,
    pub thinking_blocks: u32,
    pub redacted_thinking_blocks: u32,
    pub signature_fields: u32,
    #[serde(default)]
    pub findings: Vec<AnthropicThinkingFinding>,
}

impl AnthropicThinkingMetadata {
    pub(crate) fn record_finding(&mut self, finding: AnthropicThinkingFinding) {
        if !self.findings.contains(&finding) {
            self.findings.push(finding);
        }
    }

    pub(crate) fn finish(&mut self) {
        self.state = if !self.findings.is_empty() {
            AnthropicThinkingStructureState::Invalid
        } else if self.thinking_blocks > 0 || self.redacted_thinking_blocks > 0 {
            AnthropicThinkingStructureState::Valid
        } else {
            AnthropicThinkingStructureState::NotObserved
        };
    }
}

