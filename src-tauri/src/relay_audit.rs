pub const fn audit_budget(mode: AuditMode) -> AuditBudget {
    match mode {
        AuditMode::Connection => AuditBudget {
            fingerprint_cells: 0,
            samples_per_cell: 0,
            planned_fingerprint_requests: 0,
            hard_request_limit: 6,
        },
        AuditMode::Quick => AuditBudget {
            fingerprint_cells: 8,
            samples_per_cell: DEFAULT_SAMPLES_PER_CELL,
            planned_fingerprint_requests: 120,
            hard_request_limit: 150,
        },
        AuditMode::Standard => AuditBudget {
            fingerprint_cells: 16,
            samples_per_cell: DEFAULT_SAMPLES_PER_CELL,
            planned_fingerprint_requests: 240,
            hard_request_limit: 320,
        },
        AuditMode::Deep => AuditBudget {
            fingerprint_cells: 40,
            samples_per_cell: DEFAULT_SAMPLES_PER_CELL,
            planned_fingerprint_requests: 600,
            hard_request_limit: 720,
        },
    }
}

