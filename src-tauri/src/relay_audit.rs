//! Pure, side-effect-free primitives for XiaoLi's relay audit engine.
//!
//! This module deliberately contains no HTTP client, credential handling, file
//! I/O, database access, or Tauri calls.  A caller must obtain a 32-byte seed
//! from the operating system CSPRNG and pass it to [`generate_probe_plan`].
//! Keeping transport and scoring separate makes it possible to treat every
//! relay response as untrusted data and prevents response text from changing
//! protocol or verdict policy.
//!
//! Most importantly, none of these types contains an `actual_model` field.
//! Black-box observations can establish protocol contradictions or statistical
//! differences, but cannot prove which physical model served a request.

