#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum AuditLifecycle {
    Completed,
    Failed,
    Cancelled,
}

/// Applies the evidence boundary and stable precedence used by the UI. A
/// statistical identity difference is never upgraded to a named physical
/// model, and a single quality signal can never produce degradation.
pub fn derive_overall_verdict(
    lifecycle: AuditLifecycle,
    protocol: &ProtocolAssessment,
    usage: &UsageAssessment,
    quality: &RelayQualityAssessment,
    identity: &IdentityAssessment,
) -> OverallVerdict {
    match lifecycle {
        AuditLifecycle::Failed => return OverallVerdict::Failed,
        AuditLifecycle::Cancelled => return OverallVerdict::Cancelled,
        AuditLifecycle::Completed => {}
    }

    if protocol.state == ProtocolAssessmentKind::Abnormal
        || usage.state == UsageAssessmentKind::ContractContradiction
    {
        return OverallVerdict::ConfirmedContractMismatch;
    }
    if usage.state == UsageAssessmentKind::SuspectedOvercount {
        return OverallVerdict::SuspectedPadding;
    }
    if quality.state == QualityAssessmentKind::SuspectedDegradation {
        return OverallVerdict::SuspectedDegradation;
    }
    if quality.state == QualityAssessmentKind::SignificantlyDifferent
        || identity.state == IdentityAssessmentKind::ReferenceDifferent
    {
        return OverallVerdict::SignificantlyDifferent;
    }
    if protocol.state == ProtocolAssessmentKind::UnableToCheck
        || matches!(
            usage.state,
            UsageAssessmentKind::UsageMissing | UsageAssessmentKind::InsufficientEvidence
        )
        || matches!(
            quality.state,
            QualityAssessmentKind::Learning | QualityAssessmentKind::UnableToCheck
        )
        || matches!(
            identity.state,
            IdentityAssessmentKind::SelfReportedOnly | IdentityAssessmentKind::Unproven
        )
    {
        return OverallVerdict::InsufficientEvidence;
    }
    OverallVerdict::Consistent
}

