impl RelayAuditRequest {
    /// Refuses a request whose declared caps exceed the selected mode. A UI is
    /// free to choose smaller caps, but never silently larger ones.
    pub fn validate_budget(&self) -> Result<(), String> {
        let budget = audit_budget(self.mode);
        if self.max_requests == 0 || self.max_requests > budget.hard_request_limit {
            return Err(format!(
                "maxRequests must be between 1 and {} for {:?}",
                budget.hard_request_limit, self.mode
            ));
        }
        if self.timeout_ms == 0 {
            return Err("timeoutMs must be greater than zero".to_owned());
        }
        if self.profile_id.trim().is_empty() || self.model.trim().is_empty() {
            return Err("profileId and model are required".to_owned());
        }
        Ok(())
    }
}

