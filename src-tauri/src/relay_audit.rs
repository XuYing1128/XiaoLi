#[derive(Clone, Debug, PartialEq, Eq)]
pub enum NormalizedProbeResponse {
    Valid(String),
    Empty,
    Refusal,
    Invalid,
}

/// Normalizes a deliberately tiny answer. It does not follow instructions in
/// the response, parse JSON, open URLs, or execute a tool call.
pub fn normalize_probe_response(
    family: ProbeFamily,
    _language: ProbeLanguage,
    response: &str,
) -> NormalizedProbeResponse {
    if response.is_empty() {
        return NormalizedProbeResponse::Empty;
    }
    // Inspect only a bounded prefix. Oversized output violates the one-word
    // probe contract and must not consume unbounded memory in the scorer.
    if response.chars().count() > 256 {
        return NormalizedProbeResponse::Invalid;
    }
    let mut clean = response
        .chars()
        .filter_map(normalize_codepoint)
        .collect::<String>()
        .trim()
        .to_lowercase();
    clean = clean
        .trim_matches(|character: char| {
            matches!(
                character,
                '"' | '\''
                    | '`'
                    | '.'
                    | ','
                    | ';'
                    | ':'
                    | '!'
                    | '?'
                    | '。'
                    | '，'
                    | '！'
                    | '？'
                    | '「'
                    | '」'
                    | '『'
                    | '』'
                    | '('
                    | ')'
                    | '['
                    | ']'
                    | '{'
                    | '}'
            )
        })
        .trim()
        .to_owned();
    if clean.is_empty() {
        return NormalizedProbeResponse::Empty;
    }
    let refusal_markers = [
        "cannot",
        "can't",
        "unable",
        "refuse",
        "sorry",
        "无法",
        "不能",
        "抱歉",
        "できません",
        "申し訳",
        "no puedo",
        "lo siento",
    ];
    if refusal_markers.iter().any(|marker| clean.contains(marker)) {
        return NormalizedProbeResponse::Refusal;
    }
    if clean.chars().count() > 48
        || clean.split_whitespace().count() != 1
        || clean
            .chars()
            .any(|character| !character.is_alphanumeric() && character != '-')
    {
        return NormalizedProbeResponse::Invalid;
    }

    let canonical = match family {
        ProbeFamily::Number => canonical_number(&clean),
        ProbeFamily::Letter => canonical_letter(&clean),
        ProbeFamily::Color => canonical_color(&clean),
        _ => Some(clean),
    };
    canonical
        .map(NormalizedProbeResponse::Valid)
        .unwrap_or(NormalizedProbeResponse::Invalid)
}

fn normalize_codepoint(character: char) -> Option<char> {
    let value = character as u32;
    match value {
        0xFF10..=0xFF19 => char::from_u32(value - 0xFF10 + u32::from(b'0')),
        0xFF21..=0xFF3A => char::from_u32(value - 0xFF21 + u32::from(b'A')),
        0xFF41..=0xFF5A => char::from_u32(value - 0xFF41 + u32::from(b'a')),
        // Strip bidi overrides, isolates, zero-width marks and a BOM so they
        // cannot make UI text say something different from stored evidence.
        0x200B..=0x200F | 0x202A..=0x202E | 0x2066..=0x2069 | 0xFEFF => None,
        _ => Some(character),
    }
}

fn canonical_number(value: &str) -> Option<String> {
    if let Ok(number) = value.parse::<u16>() {
        return (1..=100).contains(&number).then(|| number.to_string());
    }
    let number = match value {
        "one" | "uno" | "一" => 1,
        "two" | "dos" | "二" => 2,
        "three" | "tres" | "三" => 3,
        "four" | "cuatro" | "四" => 4,
        "five" | "cinco" | "五" => 5,
        "six" | "seis" | "六" => 6,
        "seven" | "siete" | "七" => 7,
        "eight" | "ocho" | "八" => 8,
        "nine" | "nueve" | "九" => 9,
        "ten" | "diez" | "十" => 10,
        _ => return None,
    };
    Some(number.to_string())
}

fn canonical_letter(value: &str) -> Option<String> {
    let mut chars = value.chars();
    let character = chars.next()?;
    (chars.next().is_none() && character.is_ascii_alphabetic())
        .then(|| character.to_ascii_lowercase().to_string())
}

fn canonical_color(value: &str) -> Option<String> {
    let canonical = match value {
        "red" | "rojo" | "roja" | "红" | "红色" | "赤" => "red",
        "blue" | "azul" | "蓝" | "蓝色" | "青" => "blue",
        "green" | "verde" | "绿" | "绿色" => "green",
        "yellow" | "amarillo" | "amarilla" | "黄" | "黄色" => "yellow",
        "black" | "negro" | "negra" | "黑" | "黑色" | "黒" => "black",
        "white" | "blanco" | "blanca" | "白" | "白色" => "white",
        "gray" | "grey" | "gris" | "灰" | "灰色" => "gray",
        "purple" | "violet" | "violeta" | "morado" | "morada" | "紫" | "紫色" => "purple",
        "pink" | "rosa" | "粉" | "粉色" | "桃色" => "pink",
        "orange" | "naranja" | "橙" | "橙色" => "orange",
        "brown" | "marron" | "marrón" | "棕" | "棕色" | "茶色" => "brown",
        _ => value,
    };
    Some(canonical.to_owned())
}

#[derive(Clone, Debug, Deserialize, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct CellFingerprint {
    pub cell: ProbeCellKey,
    pub counts: BTreeMap<String, u64>,
    pub valid_count: usize,
    pub invalid_count: usize,
    pub refusal_count: usize,
    pub empty_count: usize,
}

impl CellFingerprint {
    pub fn from_responses<'a>(
        cell: ProbeCellKey,
        responses: impl IntoIterator<Item = &'a str>,
    ) -> Self {
        let mut result = Self {
            cell,
            counts: BTreeMap::new(),
            valid_count: 0,
            invalid_count: 0,
            refusal_count: 0,
            empty_count: 0,
        };
        for response in responses {
            match normalize_probe_response(cell.family, cell.language, response) {
                NormalizedProbeResponse::Valid(value) => {
                    *result.counts.entry(value).or_insert(0) += 1;
                    result.valid_count += 1;
                }
                NormalizedProbeResponse::Empty => result.empty_count += 1,
                NormalizedProbeResponse::Refusal => result.refusal_count += 1,
                NormalizedProbeResponse::Invalid => result.invalid_count += 1,
            }
        }
        result
    }

    pub fn is_eligible(&self) -> bool {
        self.valid_count >= MIN_VALID_SAMPLES_PER_CELL
    }
}

