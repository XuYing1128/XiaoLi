#[derive(Clone, Copy, Debug, Deserialize, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub enum UsageArithmeticKind {
    Valid,
    Missing,
    UnexplainedExcess,
    ContractContradiction,
}

#[derive(Clone, Debug, Deserialize, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct UsageArithmeticCheck {
    pub state: UsageArithmeticKind,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub expected_min_total: Option<i64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub unexplained_excess: Option<i64>,
    #[serde(default)]
    pub reasons: Vec<String>,
}

/// Checks only arithmetic invariants. A positive unexplained excess is not a
/// confirmed padding verdict because hidden provider-side input can exist.
pub fn check_usage_arithmetic(usage: &ReportedUsage) -> UsageArithmeticCheck {
    let fields = [
        ("inputTokens", usage.input_tokens),
        ("cachedInputTokens", usage.cached_input_tokens),
        ("outputTokens", usage.output_tokens),
        ("reasoningOutputTokens", usage.reasoning_output_tokens),
        ("totalTokens", usage.total_tokens),
    ];
    let negatives = fields
        .iter()
        .filter_map(|(name, value)| value.filter(|value| *value < 0).map(|_| *name))
        .collect::<Vec<_>>();
    if !negatives.is_empty() {
        return UsageArithmeticCheck {
            state: UsageArithmeticKind::ContractContradiction,
            expected_min_total: None,
            unexplained_excess: None,
            reasons: vec![format!("negative token count in {}", negatives.join(", "))],
        };
    }
    if matches!(
        (usage.cached_input_tokens, usage.input_tokens),
        (Some(cached), Some(input)) if cached > input
    ) {
        return UsageArithmeticCheck {
            state: UsageArithmeticKind::ContractContradiction,
            expected_min_total: None,
            unexplained_excess: None,
            reasons: vec!["cached input tokens exceed input tokens".to_owned()],
        };
    }
    if matches!(
        (usage.reasoning_output_tokens, usage.output_tokens),
        (Some(reasoning), Some(output)) if reasoning > output
    ) {
        return UsageArithmeticCheck {
            state: UsageArithmeticKind::ContractContradiction,
            expected_min_total: None,
            unexplained_excess: None,
            reasons: vec!["reasoning output tokens exceed output tokens".to_owned()],
        };
    }
    let (Some(input), Some(output), Some(total)) =
        (usage.input_tokens, usage.output_tokens, usage.total_tokens)
    else {
        return UsageArithmeticCheck {
            state: UsageArithmeticKind::Missing,
            expected_min_total: None,
            unexplained_excess: None,
            reasons: vec!["input, output, or total usage is missing".to_owned()],
        };
    };
    let Some(expected) = input.checked_add(output) else {
        return UsageArithmeticCheck {
            state: UsageArithmeticKind::ContractContradiction,
            expected_min_total: None,
            unexplained_excess: None,
            reasons: vec!["token total overflow".to_owned()],
        };
    };
    if total < expected {
        return UsageArithmeticCheck {
            state: UsageArithmeticKind::ContractContradiction,
            expected_min_total: Some(expected),
            unexplained_excess: None,
            reasons: vec!["total tokens are lower than input plus output".to_owned()],
        };
    }
    if total > expected {
        return UsageArithmeticCheck {
            state: UsageArithmeticKind::UnexplainedExcess,
            expected_min_total: Some(expected),
            unexplained_excess: Some(total - expected),
            reasons: vec![
                "total includes an unexplained excess; calibration is required before calling it padding"
                    .to_owned(),
            ],
        };
    }
    UsageArithmeticCheck {
        state: UsageArithmeticKind::Valid,
        expected_min_total: Some(expected),
        unexplained_excess: Some(0),
        reasons: Vec::new(),
    }
}

#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct UsageScaleEvidence {
    pub input_size: u64,
    pub relay_excess_tokens: Vec<f64>,
    pub reference_excess_tokens: Vec<f64>,
    pub tolerance_tokens: f64,
}

#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct UsagePaddingFactor {
    pub input_size: u64,
    pub relay_interval: ConfidenceInterval,
    pub reference_interval: ConfidenceInterval,
    pub tolerance_tokens: f64,
    pub suspicious: bool,
}

/// Requires calibrated, non-overlapping excess at two distinct input sizes.
/// An arithmetic contradiction is reported separately as a contract mismatch.
pub fn assess_usage_padding(
    arithmetic: &[UsageArithmeticCheck],
    scales: &[UsageScaleEvidence],
    seed: [u8; 32],
) -> UsageAssessment {
    if arithmetic
        .iter()
        .any(|check| check.state == UsageArithmeticKind::ContractContradiction)
    {
        return UsageAssessment {
            state: UsageAssessmentKind::ContractContradiction,
            factors: Vec::new(),
            reasons: vec!["at least one response has impossible usage arithmetic".to_owned()],
            limitations: Vec::new(),
        };
    }
    if !arithmetic.is_empty()
        && arithmetic
            .iter()
            .all(|check| check.state == UsageArithmeticKind::Missing)
    {
        return UsageAssessment {
            state: UsageAssessmentKind::UsageMissing,
            factors: Vec::new(),
            reasons: vec!["the endpoint did not provide usable token counts".to_owned()],
            limitations: Vec::new(),
        };
    }

    let mut factors = Vec::new();
    for (index, scale) in scales.iter().enumerate() {
        if scale.relay_excess_tokens.len() < MIN_PAIRED_USAGE_SAMPLES_PER_SCALE
            || scale.reference_excess_tokens.len() < MIN_PAIRED_USAGE_SAMPLES_PER_SCALE
            || !scale.tolerance_tokens.is_finite()
            || scale.tolerance_tokens < 0.0
        {
            continue;
        }
        let scale_seed = derived_seed(seed, index as u64);
        let relay_interval =
            bootstrap_mean_interval(&scale.relay_excess_tokens, scale_seed, 1_000, 0.95);
        let reference_interval = bootstrap_mean_interval(
            &scale.reference_excess_tokens,
            derived_seed(scale_seed, 1),
            1_000,
            0.95,
        );
        let (Some(relay_interval), Some(reference_interval)) = (relay_interval, reference_interval)
        else {
            continue;
        };
        let suspicious = relay_interval.lower > reference_interval.upper + scale.tolerance_tokens
            && relay_interval.lower > scale.tolerance_tokens;
        factors.push(UsagePaddingFactor {
            input_size: scale.input_size,
            relay_interval,
            reference_interval,
            tolerance_tokens: scale.tolerance_tokens,
            suspicious,
        });
    }
    if factors.is_empty() {
        return UsageAssessment {
            state: UsageAssessmentKind::InsufficientEvidence,
            factors,
            reasons: vec![
                format!(
                    "fewer than {MIN_PAIRED_USAGE_SAMPLES_PER_SCALE} paired samples were available per input size"
                ),
            ],
            limitations: vec![
                "visible token counts may omit provider-side prompts, reasoning, or transforms"
                    .to_owned(),
            ],
        };
    }
    let distinct_suspicious_sizes = factors
        .iter()
        .filter(|factor| factor.suspicious)
        .map(|factor| factor.input_size)
        .collect::<BTreeSet<_>>()
        .len();
    let state = if distinct_suspicious_sizes >= 2 {
        UsageAssessmentKind::SuspectedOvercount
    } else {
        UsageAssessmentKind::Consistent
    };
    let reasons = match distinct_suspicious_sizes {
        0 => vec!["no calibrated multi-scale overcount signal was observed".to_owned()],
        1 => {
            vec!["only one input size was anomalous; two independent sizes are required".to_owned()]
        }
        count => vec![format!(
            "calibrated excess persisted across {count} input sizes"
        )],
    };
    UsageAssessment {
        state,
        factors,
        reasons,
        limitations: vec![
            "suspected overcount is statistical evidence, not proof of intentional billing fraud"
                .to_owned(),
        ],
    }
}

#[derive(Clone, Debug, Deserialize, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct QualityCheckpoint {
    pub batch_id: String,
    /// Domains listed here must already have crossed their deterministic
    /// scorer's calibrated 99% interval. Timing, style, and cache rate are not
    /// capability domains and therefore cannot be passed here.
    #[serde(default)]
    pub failed_domains: Vec<QualityDomain>,
}

/// A content-free result from one deterministic target/reference quality
/// probe. Prompt and response text are deliberately absent.
#[derive(Clone, Debug, Deserialize, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct PairedQualityObservation {
    pub batch_id: String,
    pub domain: QualityDomain,
    pub relay_passed: bool,
    pub reference_passed: bool,
}

/// Conservative direct-pair quality assessment. Each domain is evaluated from
/// repeated paired target/reference outcomes. A domain is anomalous only when
/// the lower bound of a 99% bootstrap interval for `(reference - relay)` is
/// greater than [`PAIRED_QUALITY_GAP_TOLERANCE`]. The same two domains must
/// cross that bound in two independent batches. Reference failures are
/// excluded instead of being counted against the relay.
pub fn assess_paired_quality(
    observations: &[PairedQualityObservation],
    required_samples_per_domain: usize,
    seed: [u8; 32],
) -> RelayQualityAssessment {
    let baseline_sample_count = observations
        .iter()
        .filter(|observation| observation.reference_passed)
        .count();
    let mut grouped = BTreeMap::<(String, QualityDomain), Vec<&PairedQualityObservation>>::new();
    for observation in observations {
        grouped
            .entry((observation.batch_id.clone(), observation.domain))
            .or_default()
            .push(observation);
    }

    let mut factors = Vec::new();
    let mut eligible_by_batch = BTreeMap::<String, BTreeSet<QualityDomain>>::new();
    let mut failures_by_batch = BTreeMap::<String, BTreeSet<QualityDomain>>::new();
    for (index, ((batch_id, domain), samples)) in grouped.into_iter().enumerate() {
        let reference_valid = samples
            .into_iter()
            .filter(|sample| sample.reference_passed)
            .collect::<Vec<_>>();
        let paired_samples = reference_valid.len();
        let relay_passes = reference_valid
            .iter()
            .filter(|sample| sample.relay_passed)
            .count();
        let paired_gaps = reference_valid
            .iter()
            .map(|sample| if sample.relay_passed { 0.0 } else { 1.0 })
            .collect::<Vec<_>>();
        let interval = (paired_samples >= required_samples_per_domain)
            .then(|| {
                bootstrap_mean_interval(&paired_gaps, derived_seed(seed, index as u64), 2_000, 0.99)
            })
            .flatten();
        let suspicious = interval
            .as_ref()
            .is_some_and(|value| value.lower > PAIRED_QUALITY_GAP_TOLERANCE);
        if paired_samples >= required_samples_per_domain {
            eligible_by_batch
                .entry(batch_id.clone())
                .or_default()
                .insert(domain);
        }
        if suspicious {
            failures_by_batch
                .entry(batch_id.clone())
                .or_default()
                .insert(domain);
        }
        factors.push(PairedQualityFactor {
            batch_id,
            domain,
            relay_passes,
            reference_passes: paired_samples,
            paired_samples,
            required_samples: required_samples_per_domain,
            tolerance: PAIRED_QUALITY_GAP_TOLERANCE,
            paired_gap_interval: interval,
            suspicious,
        });
    }

    let mut batches = eligible_by_batch.keys().cloned().collect::<Vec<_>>();
    batches.sort();
    let eligible_domains = if batches.len() >= 2 {
        let left = eligible_by_batch
            .get(&batches[batches.len() - 2])
            .expect("batch key came from the map");
        let right = eligible_by_batch
            .get(&batches[batches.len() - 1])
            .expect("batch key came from the map");
        left.intersection(right).copied().collect::<BTreeSet<_>>()
    } else {
        BTreeSet::new()
    };
    if batches.len() < 2 || eligible_domains.len() < 2 {
        return RelayQualityAssessment {
            state: QualityAssessmentKind::Learning,
            baseline_sample_count,
            failed_domains: Vec::new(),
            factors,
            reasons: vec![format!(
                "learning: {required_samples_per_domain} reference-valid paired samples are required per domain and batch"
            )],
            limitations: vec![
                "paired quality evidence is unavailable when the reference itself fails".to_owned(),
            ],
        };
    }

    let left_failures = failures_by_batch
        .get(&batches[batches.len() - 2])
        .cloned()
        .unwrap_or_default();
    let right_failures = failures_by_batch
        .get(&batches[batches.len() - 1])
        .cloned()
        .unwrap_or_default();
    let persistent = left_failures
        .intersection(&right_failures)
        .filter(|domain| eligible_domains.contains(domain))
        .copied()
        .collect::<Vec<_>>();
    if persistent.len() >= 2 {
        RelayQualityAssessment {
            state: QualityAssessmentKind::SuspectedDegradation,
            baseline_sample_count,
            failed_domains: persistent.clone(),
            factors,
            reasons: vec![format!(
                "{} independent capability domains had a 99% paired gap above the {:.0}% tolerance in two batches",
                persistent.len(),
                PAIRED_QUALITY_GAP_TOLERANCE * 100.0
            )],
            limitations: vec![
                "paired statistical probes indicate a capability gap but do not identify the physical model"
                    .to_owned(),
                "a relay that recognizes audit traffic may selectively serve a different path".to_owned(),
            ],
        }
    } else {
        RelayQualityAssessment {
            state: QualityAssessmentKind::Consistent,
            baseline_sample_count,
            failed_domains: persistent,
            factors,
            reasons: vec![
                format!(
                    "no two-domain 99% paired capability gap above the {:.0}% tolerance persisted across both batches",
                    PAIRED_QUALITY_GAP_TOLERANCE * 100.0
                ),
            ],
            limitations: vec![
                "passing statistical probes is not proof of physical model identity".to_owned(),
            ],
        }
    }
}

/// A degradation warning needs at least 30 healthy baseline samples and two
/// independent capability domains recurring in two distinct batches.
pub fn assess_quality_degradation(
    baseline_sample_count: usize,
    checkpoints: &[QualityCheckpoint],
) -> RelayQualityAssessment {
    if baseline_sample_count < MIN_QUALITY_BASELINE_SAMPLES {
        return RelayQualityAssessment {
            state: QualityAssessmentKind::Learning,
            baseline_sample_count,
            failed_domains: Vec::new(),
            factors: Vec::new(),
            reasons: vec![format!(
                "learning: {baseline_sample_count}/{MIN_QUALITY_BASELINE_SAMPLES} eligible samples"
            )],
            limitations: vec![
                "quality comparison is unavailable until the baseline is ready".to_owned(),
            ],
        };
    }
    let mut latest_by_batch = Vec::<(&str, BTreeSet<QualityDomain>)>::new();
    for checkpoint in checkpoints {
        if let Some(existing) = latest_by_batch
            .iter_mut()
            .find(|(batch_id, _)| *batch_id == checkpoint.batch_id)
        {
            existing.1.extend(checkpoint.failed_domains.iter().copied());
        } else {
            latest_by_batch.push((
                checkpoint.batch_id.as_str(),
                checkpoint.failed_domains.iter().copied().collect(),
            ));
        }
    }
    let persistent = if latest_by_batch.len() >= 2 {
        let left = &latest_by_batch[latest_by_batch.len() - 2].1;
        let right = &latest_by_batch[latest_by_batch.len() - 1].1;
        left.intersection(right).copied().collect::<Vec<_>>()
    } else {
        Vec::new()
    };
    if persistent.len() >= 2 {
        RelayQualityAssessment {
            state: QualityAssessmentKind::SuspectedDegradation,
            baseline_sample_count,
            failed_domains: persistent.clone(),
            factors: Vec::new(),
            reasons: vec![format!(
                "{} independent capability domains were below baseline in two batches",
                persistent.len()
            )],
            limitations: vec![
                "behavioral degradation does not identify the physical serving model".to_owned(),
            ],
        }
    } else {
        let reason = if latest_by_batch.len() < 2 {
            "two independent batches are required"
        } else if persistent.len() == 1 {
            "only one independent capability domain persisted"
        } else {
            "no capability failures persisted across batches"
        };
        RelayQualityAssessment {
            state: QualityAssessmentKind::Consistent,
            baseline_sample_count,
            failed_domains: persistent,
            factors: Vec::new(),
            reasons: vec![reason.to_owned()],
            limitations: Vec::new(),
        }
    }
}

/// Sanitized metadata extracted by the transport layer. The protocol scorer
/// never accepts the response body, so prompt injection text cannot flip it.
#[derive(Clone, Debug, Deserialize, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct SafeResponseMetadata {
    pub http_status: u16,
    pub content_type: String,
    pub parsed_envelope: bool,
    pub streaming: bool,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub stream_terminated: Option<bool>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reported_model: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub expected_model: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub anthropic_thinking: Option<AnthropicThinkingMetadata>,
}

pub fn score_protocol_metadata(metadata: &SafeResponseMetadata) -> ProtocolAssessment {
    let mut reasons = Vec::new();
    let mut limitations = Vec::new();
    if !(200..300).contains(&metadata.http_status) {
        reasons.push(format!("HTTP status {}", metadata.http_status));
    }
    let content_type = metadata.content_type.to_ascii_lowercase();
    let valid_content_type = content_type.contains("application/json")
        || (metadata.streaming && content_type.contains("text/event-stream"));
    if !valid_content_type {
        reasons.push("unexpected response content type".to_owned());
    }
    if !metadata.parsed_envelope {
        reasons.push("response envelope does not match the selected protocol".to_owned());
    }
    if metadata.streaming && metadata.stream_terminated != Some(true) {
        reasons.push("stream did not terminate with a valid terminal event".to_owned());
    }
    if let (Some(reported), Some(expected)) = (&metadata.reported_model, &metadata.expected_model) {
        if normalize_model_id(reported) != normalize_model_id(expected) {
            reasons.push(format!(
                "response self-reported model '{}' instead of requested '{}'",
                safe_model_id(reported),
                safe_model_id(expected)
            ));
        }
    }
    if let Some(thinking) = &metadata.anthropic_thinking {
        if thinking.state != AnthropicThinkingStructureState::NotObserved {
            limitations.push(
                "Anthropic thinking fields were checked for structure and stream consistency only; opaque signature and redacted data values were not cryptographically verified"
                    .to_owned(),
            );
        }
        reasons.extend(
            thinking
                .findings
                .iter()
                .map(|finding| finding.protocol_reason().to_owned()),
        );
    }
    if reasons.is_empty() {
        ProtocolAssessment {
            state: ProtocolAssessmentKind::Normal,
            reasons,
            limitations,
        }
    } else {
        ProtocolAssessment {
            state: ProtocolAssessmentKind::Abnormal,
            reasons,
            limitations,
        }
    }
}

fn normalize_model_id(value: &str) -> String {
    value.trim().to_ascii_lowercase()
}

#[derive(Clone, Debug)]
struct DeterministicRng {
    state: u64,
}

impl DeterministicRng {
    fn from_seed(seed: [u8; 32]) -> Self {
        let mut state = 0x6a09_e667_f3bc_c909_u64;
        for chunk in seed.chunks_exact(8) {
            let mut bytes = [0_u8; 8];
            bytes.copy_from_slice(chunk);
            state ^= u64::from_le_bytes(bytes);
            state = splitmix64(state);
        }
        Self { state }
    }

    fn next_u64(&mut self) -> u64 {
        self.state = self.state.wrapping_add(0x9e37_79b9_7f4a_7c15);
        splitmix64(self.state)
    }

    fn gen_range(&mut self, upper: usize) -> usize {
        assert!(upper > 0, "upper bound must be positive");
        // Rejection avoids modulo bias, even though this RNG is used for
        // deterministic plan derivation rather than cryptography.
        let zone = u64::MAX - (u64::MAX % upper as u64);
        loop {
            let value = self.next_u64();
            if value < zone {
                return (value % upper as u64) as usize;
            }
        }
    }

    fn shuffle<T>(&mut self, values: &mut [T]) {
        for index in (1..values.len()).rev() {
            let selected = self.gen_range(index + 1);
            values.swap(index, selected);
        }
    }
}

fn splitmix64(mut value: u64) -> u64 {
    value = (value ^ (value >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
    value = (value ^ (value >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
    value ^ (value >> 31)
}

fn derived_seed(mut seed: [u8; 32], domain: u64) -> [u8; 32] {
    let mixed = splitmix64(domain ^ u64::from_le_bytes(seed[0..8].try_into().unwrap()));
    for (target, source) in seed[0..8].iter_mut().zip(mixed.to_le_bytes()) {
        *target ^= source;
    }
    seed
}

