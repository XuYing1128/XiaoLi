    #[test]
    fn paired_quality_requires_reference_valid_two_domain_failures_in_two_batches() {
        let mut observations = Vec::new();
        for batch in ["a", "b"] {
            for domain in [QualityDomain::StructuredOutput, QualityDomain::Multilingual] {
                for _ in 0..5 {
                    observations.push(PairedQualityObservation {
                        batch_id: batch.to_owned(),
                        domain,
                        relay_passed: false,
                        reference_passed: true,
                    });
                }
            }
        }
        let degraded = assess_paired_quality(&observations, 5, seed(44));
        assert_eq!(degraded.state, QualityAssessmentKind::SuspectedDegradation);
        assert_eq!(degraded.failed_domains.len(), 2);
        assert!(degraded.factors.iter().all(|factor| {
            factor.tolerance == PAIRED_QUALITY_GAP_TOLERANCE
                && factor.paired_gap_interval.as_ref().is_some_and(|interval| {
                    interval.confidence == 0.99 && interval.lower > PAIRED_QUALITY_GAP_TOLERANCE
                })
        }));

        for observation in &mut observations {
            if observation.domain == QualityDomain::StructuredOutput {
                observation.reference_passed = false;
            }
        }
        let unavailable = assess_paired_quality(&observations, 5, seed(44));
        assert_ne!(
            unavailable.state,
            QualityAssessmentKind::SuspectedDegradation
        );
    }

